// Renders docs/cutscenes.md from the catalog.

const { scenarioName } = require("./names");

const CLASS_TEXT = {
    a: "story or scripted cutscene",
    b: "boss or mini-boss",
    c: "NPC conversation with a camera or demo",
    d: "repeatable system event",
};

const cell = (s) => String(s ?? "").replace(/\|/g, "/").replace(/\r?\n/g, " ");
const where = (e) => {
    if (e.stage) return `${e.stage}${e.room >= 0 ? ` r${e.room}` : e.room === -1 ? " (stage)" : ""}${e.place ? `, ${e.place}` : ""}`;
    const w = e.when?.[0];
    return w ? `${w.stage} r${w.room}${e.place ? `, ${e.place}` : ""}` : e.arc ? `${e.arc}.arc` : "";
};

function triggerText(e) {
    const parts = [];
    for (const t of e.triggers) {
        if (t.kind === "arrival") parts.push(`arrive at point ${t.point} (r${t.room})`);
        else if (t.kind === "tag") {
            const a = t.area.shape === "box" ? `box ${t.area.x}x${t.area.y}x${t.area.z}` : `r ${t.area.radius} h ${t.area.height}`;
            parts.push(`walk into ${t.actor} (${a}) at ${t.pos.join(",")}${t.layer >= 0 ? ` L${t.layer}` : ""}`);
        } else if (t.kind === "actor") parts.push(`${t.actor}: ${t.trigger ? t.trigger.split(/[;.]/)[0] : "orders it"}`);
        else if (t.kind === "chain") parts.push(`after ${t.from} (next)`);
        else if (t.kind === "named") parts.push(`ordered by name in ${t.file}${t.placements.length ? "" : " (not placed here)"}`);
        else if (t.kind === "actor-event") parts.push(`${t.file.replace(/^d_a_|\.cpp$/g, "")}${t.npcIndex ? ` entry ${t.npcIndex}` : ""}`);
        else if (t.kind === "boss") parts.push(`${t.file}, own camera`);
    }
    const uniq = [...new Set(parts)];
    return uniq.length ? uniq.slice(0, 3).join("; ") + (uniq.length > 3 ? `; +${uniq.length - 3}` : "") : "unverified: no placed trigger found";
}

function whenText(e, milestoneText) {
    const seen = new Set();
    const out = [];
    for (const w of e.when ?? []) {
        if (!w.milestone) {
            out.push("unverified");
            continue;
        }
        const s = `${milestoneText(w.milestone)}, layer ${w.layer}${w.natural === false ? " (explicit)" : ""}${w.night ? ", night" : ""}${w.stage && w.stage !== e.stage ? ` in ${w.stage} r${w.room}` : ""}`;
        if (!seen.has(s)) {
            seen.add(s);
            out.push(s);
        }
    }
    const conds = [...new Set((e.when ?? []).flatMap((w) => w.conditions ?? []))];
    let text = out.slice(0, 2).join("; ") + (out.length > 2 ? `; +${out.length - 2}` : "");
    if (conds.length) text += `; ${conds.slice(0, 3).join(", ")}`;
    return text || "unverified";
}

function setsText(e) {
    const s = [];
    if (e.switchNo !== undefined && e.switchNo !== 0xff) s.push(`switch ${e.switchNo}`);
    for (const t of e.triggers) if (t.kind === "tag" && t.swbit !== 0xff) s.push(`switch ${t.swbit}`);
    if (e.dest) s.push(`goes to ${e.dest.stage} r${e.dest.room} p${e.dest.point}${e.dest.layer >= 0 ? ` L${e.dest.layer}` : ""}`);
    else if (e.relocates) s.push("stage change (in code)");
    if (e.summary?.stb) s.push(`plays ${e.summary.stb}.stb`);
    return [...new Set(s)].join("; ") || "-";
}

function modText(e) {
    const p = e.mod.pullIn === "no" ? `no (${e.mod.refusal})` : e.mod.pullIn;
    const els = e.mod.elsewhere.startsWith("none") ? "elsewhere: none" : `elsewhere: ${e.mod.elsewhere}`;
    return `same room: ${p}; ${els}`;
}

function renderDocs(catalog) {
    const milestoneText = (id) => id;
    const all = catalog.cutscenes;
    const scoped = all.filter((e) => e.class !== "d");
    const regions = [...new Set(all.map((e) => e.region))];
    const lines = [];
    const push = (...l) => lines.push(...l);

    push("# Cutscenes", "",
        "Every event the game can start, from the disc image and the decomp, with where and when it starts and",
        "what Twili-Together does with it today. Generated by `node tools/cutscenes/extract.js` (about two seconds;",
        "it reads the disc image named in the user's config, read only, and the decomp sources of the Dusklight",
        "tree around this mod). The same data, for scripts, is `tools/autotest/data/cutscenes.json`; the test",
        "scenarios built from it are in `tools/autotest/scenarios/cutscenes.js`.", "");

    push("## Counts", "", "| Region | a | b | c | d |", "| --- | --- | --- | --- | --- |");
    for (const r of regions) {
        const n = (c) => all.filter((e) => e.region === r && e.class === c).length;
        push(`| ${r} | ${n("a")} | ${n("b")} | ${n("c")} | ${n("d")} |`);
    }
    const tot = (c) => all.filter((e) => e.class === c).length;
    push(`| **All** | ${tot("a")} | ${tot("b")} | ${tot("c")} | ${tot("d")} |`, "");

    push("## How the map is built", "",
        "- **Disc**: the GameCube file table, Yaz0 and RARC (`gc.js`); per stage `stage.dzs` and each `room.dzr`",
        "  (`stage.js`): actors of every layer (ACTR/TGOB/SCOB/TRES and ACT0-e, SCO0-e), PLYR start points, SCLS",
        "  exits, REVT map events, LBNK demo banks, and every `event_list.dat` (stage, rooms, `Event.arc` and the",
        "  actor archives).",
        "- **Map events** (REVT): one row per entry. Its triggers are the PLYR points whose start event (params",
        "  >> 24) names it, the daTag_Event_c (TagEv) tags whose event number names it, and the other placed actors",
        "  whose map-tool id (decoded with `tools/cutscenes/decoders.json`, read from each actor's source) names it.",
        "  An STB demo kept in a Demo archive only plays on the layers whose LBNK bank loads that archive.",
        "- **Named events**: stage and room list events no map event names; their requesters are the actor",
        "  sources that spell the name. **Actor events**: each actor archive's list, matched to the actor source",
        "  whose resource list and event table name it (daNpcT_c tables give the entry index).",
        "- **Bosses** run their intros and deaths on potential events with their own camera (no event data).",
        "- **When**: `layers.js` transcribes `getLayerNo_common_common` and the twilight table, and walks a list of",
        "  story milestones (below); a trigger's recipe is the first milestone from the stage's first visit whose",
        "  flags pick a layer the trigger exists on, with the trigger's own event-bit terms added. A layer no flags",
        "  pick is a cutscene layer that a scene exit or an event names: those recipes say *explicit* and their",
        "  flags are approximate. An arrival reached by another cutscene's exit is placed after it.",
        "- **Mod today**: StoryEvent.cpp's rules, applied statically (next section).", "");

    push("## Story milestones", "", "Recipes name the milestone whose flags (all those before it, too) they start from.", "");
    for (const m of catalog.milestones) push(`- \`${m.id}\`: ${m.text}`);
    push("");

    // Gap analysis.
    const cnt = (f) => scoped.filter(f).length;
    const refusals = {};
    for (const e of scoped) if (e.mod.refusal) refusals[e.mod.refusal] = (refusals[e.mod.refusal] ?? 0) + 1;
    push("## Gap analysis", "",
        `Classes a to c: ${scoped.length} events. Same-room pull-in (STORY_EVENT) likely: ${cnt((e) => e.mod.pullIn === "likely")};`,
        `refused by a rule: ${cnt((e) => e.mod.pullIn === "no")}; trigger not found statically: ${cnt((e) => e.mod.pullIn === "unverified")}.`, "",
        "| Refusal | Events | Why |", "| --- | --- | --- |");
    const why = {
        "npc-not-allowlisted": "NPC table events need an allowlist entry (kNpcJoinable is empty)",
        "npc-unknown-entry": "a daNpcT_c event whose table entry was not found statically (refused unless the entry is known)",
        "actor-requester": "a placed actor (switch, door, object, Midna hint) orders the map event with itself as requester",
        "repeatable-arrival": "an arrival demo with no switch and no exit is treated as scenery",
        "not-a-map-event": "ordered by name (map-tool id 0xFF), so B cannot look it up in its own REVT table",
        "list": "the event lives in an actor's own list (BASE_ACTOR: NPCs outside daNpcT_c, objects) or the common list",
        "not-a-demo": "a potential event with its own camera (bosses)",
        camera: "a map-tool camera, not a ZEV or STB event",
    };
    for (const [k, v] of Object.entries(refusals).sort((a, b) => b[1] - a[1])) push(`| ${k} | ${v} | ${why[k] ?? ""} |`);
    push("",
        "Pulled in when likely means: the originator's instance passes notJoinable (an OTHER event with a map-tool",
        "id, from the stage, room or demo list, a ZEV or STB map event, requested by nobody, the player or an event",
        "tag, and an arrival only when it has a switch or an exit). B then also needs the same stage, layer and",
        "room, the same map event and name in its own tables, no event running, its switch still off (else `seen`),",
        "its own tag passing its trigger terms, the same form, and a safe stance (not swimming, airborne, in a menu",
        "or loading). The generated scenarios start both players on the same checkpoint, so only the first part",
        "decides.", "",
        "Elsewhere: a teammate in another room only hears of a cutscene that changes the stage (a story move). A",
        "strong move (curated, a side-effect entrance, a form or level change, a boss clear) brings the follow",
        "prompt; a weak one only a menu row and a toast. Cutscenes that stay in the room send no move: their flags",
        "reach the teammate by world sync, which is the design.", "");

    const likelyBroken = scoped.filter((e) => e.class === "a" && e.mod.pullIn === "no" && e.mod.refusal !== "repeatable-arrival");
    push("### Story cutscenes likely broken today", "",
        "Class a events a same-room teammate would not see, with the rule that refuses them:", "");
    for (const e of likelyBroken) push(`- \`${e.id}\` ${e.name} (${where(e)}): ${e.mod.refusal}; ${triggerText(e)}`);
    push("");

    push("## Legend", "",
        "- **Class**: a = story or scripted, b = boss or mini-boss, c = NPC conversation or Midna hint with a camera,",
        "  d = repeatable system event (doors, chests, warps, save, cameras on switches), listed but not tested.",
        "- **Trigger**: arrive at point N (a PLYR start event; the arrival layer comes from the exits that lead",
        "  there), walk into a tag (TagEv area: box sizes or cylinder radius and height, in units), an actor that",
        "  orders it, `next` from another map event, ordered by name from code, an NPC table entry.",
        "- **When**: milestone, layer (explicit when no flags pick it), night when the layer needs it, then the",
        "  trigger's own terms. **Sets**: switches and stage changes decoded statically; event bits set by actor",
        "  code are not decoded.",
        "- **Test**: the generated scenario (`node tools/autotest/run.js <name>`); `-` when no recipe could be built.", "");

    for (const r of regions) {
        const rows = scoped.filter((e) => e.region === r);
        if (!rows.length) continue;
        push(`## ${r}`, "");
        const story = rows.filter((e) => e.source !== "actor");
        if (story.length) {
            push("| Cutscene | Where | Trigger | When | Sets | Class | Mod today | Test |", "| --- | --- | --- | --- | --- | --- | --- | --- |");
            for (const e of story) {
                push(`| \`${cell(e.id)}\` ${cell(e.name)} (${e.mapType ?? e.source}) | ${cell(where(e))} | ${cell(triggerText(e))} | ${cell(whenText(e, milestoneText))} | ${cell(setsText(e))} | ${e.class} | ${cell(modText(e))} | ${e.test ? `\`${scenarioName(e)}\`` : "-"} |`);
            }
            push("");
        }
        const npc = rows.filter((e) => e.source === "actor");
        if (npc.length) {
            push(`### ${r}: NPC and actor events`, "", "| Event | Where | Requester | When | Mod today | Test |", "| --- | --- | --- | --- | --- | --- |");
            for (const e of npc) {
                push(`| \`${cell(e.id)}\` | ${cell(where(e))} | ${cell(triggerText(e))} | ${cell(whenText(e, milestoneText))} | ${cell(modText(e))} | ${e.test ? `\`${scenarioName(e)}\`` : "-"} |`);
            }
            push("");
        }
    }

    push("## System events (class d)", "", "Listed, not tested. Map-tool cameras per stage, then the rest by name.", "");
    const cams = {};
    for (const e of all.filter((x) => x.class === "d" && x.mapType === "camera")) cams[e.stage] = (cams[e.stage] ?? 0) + 1;
    push(Object.entries(cams).map(([s, n]) => `${s} ${n}`).join(", "), "");
    const rest = all.filter((x) => x.class === "d" && x.mapType !== "camera");
    const byWhy = {};
    for (const e of rest) (byWhy[e.classWhy.replace(/ \w+$/, (m) => (e.source === "actor" ? "" : m))] ??= []).push(e);
    for (const [k, list] of Object.entries(byWhy)) {
        push(`- **${k}** (${list.length}): ${list.map((e) => `\`${e.id}\``).join(", ")}`);
    }
    push("");
    return lines.join("\n");
}

module.exports = { renderDocs };
